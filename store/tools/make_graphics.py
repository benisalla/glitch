#!/usr/bin/env python3
"""Single source of truth for the Glitch icon artwork.

Generates, from one geometry definition:
  - app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml
  - store/graphics/icon.svg, store/graphics/feature-graphic.svg
  - store/graphics/icon-512.png       (Play Store hi-res icon, 512x512, 32-bit PNG)
  - store/graphics/feature-graphic.png (Play Store feature graphic, 1024x500, 24-bit PNG)

Requires Python 3 and Pillow (`pip install pillow`). PNGs are drawn directly with
Pillow (4x supersampled), so no SVG converter is needed. Run from the repo root:

    python3 store/tools/make_graphics.py
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res/drawable"
OUT = ROOT / "store/graphics"

# Colors (background matches @color/ic_launcher_background).
BG = "#2E3A59"
TILE = "#FFFFFF"
ACCENT = "#FFC857"
TEXT_SOFT = "#C9D1E6"

# Geometry in adaptive-icon units (108 x 108 canvas, 66-unit safe zone centred at 54,54).
# A 3x3 grid of app tiles; the middle tile is "shuffled": accent coloured and tilted.
TILE_SIZE = 10.0
GAP = 3.0
RADIUS = 2.5
ORIGIN = 54 - (3 * TILE_SIZE + 2 * GAP) / 2  # 36 -> grid spans 36..72
TILT = 25.0  # degrees, middle tile only


def tiles():
    """Yield (x, y, color, rotation_degrees) for each tile, in 108-unit space."""
    for row in range(3):
        for col in range(3):
            x = ORIGIN + col * (TILE_SIZE + GAP)
            y = ORIGIN + row * (TILE_SIZE + GAP)
            if row == 1 and col == 1:
                yield x, y, ACCENT, TILT
            else:
                yield x, y, TILE, 0.0


def fmt(v):
    return f"{v:g}"


def rounded_rect_path(x, y, s=TILE_SIZE, r=RADIUS):
    inner = s - 2 * r
    return (
        f"M{fmt(x + r)},{fmt(y)}h{fmt(inner)}"
        f"a{fmt(r)},{fmt(r)} 0,0 1,{fmt(r)},{fmt(r)}v{fmt(inner)}"
        f"a{fmt(r)},{fmt(r)} 0,0 1,{fmt(-r)},{fmt(r)}h{fmt(-inner)}"
        f"a{fmt(r)},{fmt(r)} 0,0 1,{fmt(-r)},{fmt(-r)}v{fmt(-inner)}"
        f"a{fmt(r)},{fmt(r)} 0,0 1,{fmt(r)},{fmt(-r)}z"
    )


# ---------------------------------------------------------------- Android vectors

VECTOR_HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by store/tools/make_graphics.py. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
"""


def vector_tiles(mono):
    flat = [t for t in tiles() if t[3] == 0]
    tilted = [t for t in tiles() if t[3] != 0]
    color = "#FFFFFFFF" if mono else "#FF" + TILE[1:]
    out = "    <!-- Eight app tiles, all inside the 66dp safe zone (grid spans 36..72). -->\n"
    out += f'    <path\n        android:fillColor="{color}"\n        android:pathData="'
    out += "".join(rounded_rect_path(x, y) for x, y, _, _ in flat) + '" />\n'
    for x, y, c, rot in tilted:
        fill = "#FFFFFFFF" if mono else "#FF" + c[1:]
        out += "    <!-- The shuffled tile: tilted around the icon centre. -->\n"
        out += (
            f'    <group\n        android:pivotX="54"\n        android:pivotY="54"\n'
            f'        android:rotation="{fmt(rot)}">\n'
            f'        <path\n            android:fillColor="{fill}"\n'
            f'            android:pathData="{rounded_rect_path(x, y)}" />\n    </group>\n'
        )
    return out


def write_vectors():
    (RES / "ic_launcher_background.xml").write_text(
        VECTOR_HEAD
        + '    <path\n        android:fillColor="@color/ic_launcher_background"\n'
        + '        android:pathData="M0,0h108v108h-108z" />\n</vector>\n'
    )
    (RES / "ic_launcher_foreground.xml").write_text(VECTOR_HEAD + vector_tiles(False) + "</vector>\n")
    (RES / "ic_launcher_monochrome.xml").write_text(VECTOR_HEAD + vector_tiles(True) + "</vector>\n")


# ---------------------------------------------------------------- SVG

def svg_tiles(scale, dx, dy):
    parts = []
    for x, y, c, rot in tiles():
        cx, cy = dx + 54 * scale, dy + 54 * scale
        transform = f' transform="rotate({fmt(rot)} {fmt(cx)} {fmt(cy)})"' if rot else ""
        parts.append(
            f'  <rect x="{fmt(dx + x * scale)}" y="{fmt(dy + y * scale)}" '
            f'width="{fmt(TILE_SIZE * scale)}" height="{fmt(TILE_SIZE * scale)}" '
            f'rx="{fmt(RADIUS * scale)}" fill="{c}"{transform}/>'
        )
    return "\n".join(parts)


# Play icon: show the same 72-unit area a launcher shows (units 18..90) at 512 px.
ICON_PX = 512
ICON_SCALE = ICON_PX / 72
ICON_OFFSET = -18 * ICON_SCALE

# Feature graphic layout.
FG_W, FG_H = 1024, 500
FG_GRID_SCALE = 6.4  # 36-unit grid -> ~230 px
FG_GRID_CX, FG_GRID_CY = 250, 250
TITLE = "Glitch"
TAGLINE = ["Glitch the autopilot.", "Look, then tap."]
FOOTER = "No permissions · No internet · No tracking"
FONT_BOLD = "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf"
FONT_REG = "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf"
TEXT_X = 470


def write_svgs():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "icon.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{ICON_PX}" height="{ICON_PX}" '
        f'viewBox="0 0 {ICON_PX} {ICON_PX}">\n'
        f'  <rect width="{ICON_PX}" height="{ICON_PX}" fill="{BG}"/>\n'
        f"{svg_tiles(ICON_SCALE, ICON_OFFSET, ICON_OFFSET)}\n</svg>\n"
    )
    dx = FG_GRID_CX - 54 * FG_GRID_SCALE
    dy = FG_GRID_CY - 54 * FG_GRID_SCALE
    (OUT / "feature-graphic.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{FG_W}" height="{FG_H}" '
        f'viewBox="0 0 {FG_W} {FG_H}">\n'
        f'  <rect width="{FG_W}" height="{FG_H}" fill="{BG}"/>\n'
        f"{svg_tiles(FG_GRID_SCALE, dx, dy)}\n"
        f'  <g font-family="Noto Sans, sans-serif">\n'
        f'    <text x="{TEXT_X}" y="205" font-size="72" font-weight="700" fill="{TILE}">{TITLE}</text>\n'
        f'    <text x="{TEXT_X}" y="268" font-size="34" fill="{TEXT_SOFT}">{TAGLINE[0]}</text>\n'
        f'    <text x="{TEXT_X}" y="312" font-size="34" fill="{TEXT_SOFT}">{TAGLINE[1]}</text>\n'
        f'    <text x="{TEXT_X}" y="372" font-size="22" font-weight="700" fill="{ACCENT}">{FOOTER}</text>\n'
        f"  </g>\n</svg>\n"
    )


# ---------------------------------------------------------------- PNG (Pillow)

SS = 4  # supersampling factor


def tile_polygon(x, y, rot, scale, dx, dy):
    """Rounded square as a polygon (arcs sampled), rotated about the icon centre."""
    pts = []
    corners = [  # arc centre, start angle
        (x + TILE_SIZE - RADIUS, y + RADIUS, -90),
        (x + TILE_SIZE - RADIUS, y + TILE_SIZE - RADIUS, 0),
        (x + RADIUS, y + TILE_SIZE - RADIUS, 90),
        (x + RADIUS, y + RADIUS, 180),
    ]
    for cx, cy, start in corners:
        for i in range(17):
            a = math.radians(start + 90 * i / 16)
            pts.append((cx + RADIUS * math.cos(a), cy + RADIUS * math.sin(a)))
    t = math.radians(rot)
    out = []
    for px, py in pts:
        rx = 54 + (px - 54) * math.cos(t) - (py - 54) * math.sin(t)
        ry = 54 + (px - 54) * math.sin(t) + (py - 54) * math.cos(t)
        out.append(((dx + rx * scale) * SS, (dy + ry * scale) * SS))
    return out


def draw_tiles(draw, scale, dx, dy):
    for x, y, c, rot in tiles():
        draw.polygon(tile_polygon(x, y, rot, scale, dx, dy), fill=c)


def write_pngs():
    img = Image.new("RGBA", (ICON_PX * SS, ICON_PX * SS), BG)
    draw_tiles(ImageDraw.Draw(img), ICON_SCALE, ICON_OFFSET, ICON_OFFSET)
    img.resize((ICON_PX, ICON_PX), Image.LANCZOS).save(OUT / "icon-512.png", optimize=True)

    img = Image.new("RGB", (FG_W * SS, FG_H * SS), BG)
    d = ImageDraw.Draw(img)
    draw_tiles(d, FG_GRID_SCALE, FG_GRID_CX - 54 * FG_GRID_SCALE, FG_GRID_CY - 54 * FG_GRID_SCALE)
    bold = lambda s: ImageFont.truetype(FONT_BOLD, s * SS)
    reg = lambda s: ImageFont.truetype(FONT_REG, s * SS)
    # y values are text baselines, matching the SVG.
    d.text((TEXT_X * SS, 205 * SS), TITLE, font=bold(72), fill=TILE, anchor="ls")
    d.text((TEXT_X * SS, 268 * SS), TAGLINE[0], font=reg(34), fill=TEXT_SOFT, anchor="ls")
    d.text((TEXT_X * SS, 312 * SS), TAGLINE[1], font=reg(34), fill=TEXT_SOFT, anchor="ls")
    d.text((TEXT_X * SS, 372 * SS), FOOTER, font=bold(22), fill=ACCENT, anchor="ls")
    for text, font in [(TITLE, bold(72)), (TAGLINE[0], reg(34)), (FOOTER, bold(22))]:
        right = d.textbbox((TEXT_X * SS, 0), text, font=font)[2] / SS
        assert right < FG_W - 40, f"text overflows feature graphic: {text!r} ends at {right}"
    img.resize((FG_W, FG_H), Image.LANCZOS).save(OUT / "feature-graphic.png", optimize=True)


if __name__ == "__main__":
    write_vectors()
    write_svgs()
    write_pngs()
    print("Wrote vectors to", RES.relative_to(ROOT), "and graphics to", OUT.relative_to(ROOT))
